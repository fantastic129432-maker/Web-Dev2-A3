/**
 * js/event.js
 * ---------------------------------------------------------------------------
 * Event detail page controller.
 *
 * Required behaviour from the assessment brief, and where it happens here:
 *   * "only displays the details for the specific event selected from the Home
 *      or Search pages ... utilise URL query strings or Local Storage to pass
 *      the event id and fetch the correct data via your API"
 *        -> readEventId() reads ?id=7; the last id the visitor opened is also
 *           remembered in localStorage as a fallback, so the page still works
 *           if the query string is lost.
 *   * "display all relevant event details retrieved from your API with a
 *      professional and engaging layout"
 *        -> renderEvent() builds the hero, the facts list, the full
 *           description, the purpose and the organisation panel.
 *   * "ticket information (the price, or even a free one)"
 *        -> buildTicketPanel() lists every ticket tier and marks free tiers.
 *   * "Goal vs. Progress (for a specific charity goal)"
 *        -> dom.js progressBar() draws the goal against the donations total.
 *
 * Assessment 3 additions
 *   * The Register button now LINKS to registration.html?id=<id> instead of
 *     opening the "under construction" dialog. The brief requires it to
 *     "correctly link to the new Event Registration Page".
 *   * The inline demonstration form that A2 carried has been REMOVED from this
 *     page. It was a non-functional placeholder, and A3 gives registration a
 *     dedicated page - keeping a second, dead form here would be confusing.
 *   * A new panel lists the registrations for the event, retrieved through
 *     GET /api/events/:id (which A3 extended to include them), newest purchase
 *     first.
 *   * An optional weather panel shows the Open-Meteo forecast for the event day.
 */
import { getEventById, ApiError } from './api.js';
import { initLayout } from './nav.js';
import {
  el,
  select,
  imageUrl,
  stateBadge,
  progressBar,
  formatDate,
  formatDateRange,
  formatShortDate,
  formatTime,
  formatPrice,
  formatCurrency,
  showError,
} from './dom.js';
import { REGISTRATION_PAGE } from './config.js';
import { fetchEventForecast, weatherCodeKey, weatherGlyph, isWetWeather } from './weather.js';
import { t, onLanguageChange } from './i18n.js';

const STORAGE_KEY = 'charity-events:last-viewed-event-id';

/* ------------------------------------------------------------------ */
/* Startup                                                             */
/* ------------------------------------------------------------------ */
document.addEventListener('DOMContentLoaded', () => {
  initLayout();

  const eventId = readEventId();

  if (!eventId) {
    renderMissingId();
  } else {
    loadEvent(eventId);
  }

  // The whole detail page is generated by this module, so a language change has
  // to rebuild it from the data that is already in memory rather than re-fetch.
  onLanguageChange(() => {
    if (currentEvent) {
      renderEvent(currentEvent);
    } else {
      renderMissingId();
    }
    appendBackLink(select('#event-root'));
  });
});

/** The event currently on screen, kept so a language change can re-render it. */
let currentEvent = null;

/**
 * The forecast already fetched for the current event, so a language change
 * rebuilds the panel from memory instead of calling Open-Meteo again.
 */
let currentForecast = null;

/** Aborts an in-flight forecast request when a new event is opened. */
let forecastController = null;

/* ------------------------------------------------------------------ */
/* Reading the event id                                                */
/* ------------------------------------------------------------------ */

/**
 * Get the event id, preferring the query string (the method the brief
 * suggests) and falling back to localStorage.
 */
function readEventId() {
  const fromQuery = new URLSearchParams(window.location.search).get('id');

  if (fromQuery !== null && fromQuery !== '') {
    // Remember it for a later visit without the query string.
    try {
      window.localStorage.setItem(STORAGE_KEY, fromQuery);
    } catch (error) {
      // Private browsing can block localStorage; the query string still works.
    }
    return fromQuery;
  }

  try {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored) {
      // Put the id back into the address bar so the URL stays shareable.
      window.history.replaceState({}, '', `?id=${encodeURIComponent(stored)}`);
      return stored;
    }
  } catch (error) {
    // ignore
  }

  return null;
}

/* ------------------------------------------------------------------ */
/* Loading and rendering                                               */
/* ------------------------------------------------------------------ */
async function loadEvent(eventId) {
  const root = select('#event-root');

  try {
    const event = await getEventById(eventId);
    renderEvent(event);
    loadForecast(event);
  } catch (error) {
    if (error instanceof ApiError && error.status === 404) {
      showError(root, error.message, [t('error.eventSuspendedHint')]);
    } else {
      showError(root, error.friendlyMessage || t('error.eventLoadFailed'), error.details);
    }
    appendBackLink(root);
  }
}

/**
 * Fetch the optional forecast and swap the placeholder panel for the result.
 *
 * Kept separate from renderEvent() on purpose: the forecast is a bonus, so it
 * must never delay or break the event details, and a language change must not
 * trigger another network call.
 */
async function loadForecast(event) {
  if (forecastController) forecastController.abort();
  forecastController = new AbortController();

  const placeholder = select('#weather-panel');
  if (!placeholder) return;

  currentForecast = await fetchEventForecast(event, {
    signal: forecastController.signal,
  });

  // The visitor may have navigated (or the language may have changed) while the
  // request was in flight, in which case the placeholder is gone.
  const target = select('#weather-panel');
  if (!target || !currentEvent || currentEvent.eventId !== event.eventId) return;

  if (currentForecast) {
    target.replaceWith(buildWeatherPanel(event, currentForecast));
  } else {
    // Remove the placeholder entirely: either the venue has no coordinates, the
    // event is too far away, or the weather service is unreachable. None of
    // those deserve an error box on a page that is otherwise fine.
    target.remove();
  }
}

/** Build the complete page for one event. */
function renderEvent(event) {
  const root = select('#event-root');

  currentEvent = event;
  document.title = t('event.detailTitle', { name: event.eventName });
  select('#breadcrumb-event').textContent = event.eventName;

  root.replaceChildren(buildHero(event), buildDetailSection(event));

  // A re-render (a language change) has to restore the forecast panel too.
  if (currentForecast) {
    const placeholder = select('#weather-panel');
    if (placeholder) placeholder.replaceWith(buildWeatherPanel(event, currentForecast));
  }
}

/* ------------------------------------------------------------------ */
/* Hero                                                                */
/* ------------------------------------------------------------------ */
function buildHero(event) {
  const section = el('section', { className: 'event-hero' });
  const container = el('div', { className: 'container' });
  const grid = el('div', { className: 'event-hero__grid' });

  /* --- left: the headline facts ---------------------------------- */
  const copy = el('div');

  const meta = el('div', { className: 'event-hero__meta' });
  meta.append(stateBadge(event.eventState));
  meta.append(
    el('span', {
      className: 'chip',
      text: event.categoryName || t('state.charityEvent'),
    })
  );
  meta.append(
    el('span', {
      className: 'price',
      text: priceSummary(event),
    })
  );

  const title = el('h1', { text: event.eventName });

  const lead = el('p', { className: 'event-hero__lead', text: event.shortDescription });

  const facts = el('ul', { className: 'fact-list' });
  [
    [t('event.detailDate'), formatDate(event.dateStart)],
    [t('event.detailTime'), `${formatTime(event.startTime)} - ${formatTime(event.endTime)}`],
    [
      t('event.detailVenue'),
      `${event.venueName}${event.address && event.address !== 'N/A' ? `, ${event.address}` : ''}`,
    ],
    [t('event.detailLocation'), `${event.city} ${event.state || ''} ${event.postcode || ''}`.trim()],
    [t('event.detailOrganiser'), event.organizationName],
    [
      t('event.detailCapacity'),
      event.capacity
        ? t('event.capacityPlaces', { count: event.capacity })
        : t('event.capacityUnlimited'),
    ],
    // A3: how many registrations the event has attracted so far.
    [
      t('event.registrationsTotal'),
      t('event.registeredCount', { count: event.registrationCount || 0 }),
    ],
  ].forEach(([label, value]) => {
    const item = el('li');
    item.append(
      el('span', { className: 'fact-list__label', text: label }),
      el('span', { className: 'fact-list__value', text: value })
    );
    facts.append(item);
  });

  copy.append(meta, title, lead, facts);

  /* --- right: image ---------------------------------------------- */
  const media = el('div', { className: 'event-hero__media' });
  media.append(
    el('img', {
      attributes: {
        src: imageUrl(event),
        alt: t('a11y.eventIllustration', { name: event.eventName }),
        width: '720',
        height: '450',
      },
    })
  );

  grid.append(copy, media);
  container.append(grid);
  section.append(container);
  return section;
}

/** "Free entry", "From $20.00" or "Tickets from $20.00 to $480.00". */
function priceSummary(event) {
  const prices = (event.ticketTypes || []).map((ticket) => ticket.price);

  if (event.isFree || (prices.length > 0 && prices.every((price) => price === 0))) {
    return t('event.freeEntry');
  }
  if (prices.length === 0) {
    return t('event.contactForPrices');
  }

  const min = Math.min(...prices.filter((price) => price > 0));
  const max = Math.max(...prices);
  if (min === max) return t('event.ticketsSingle', { price: formatPrice(min) });
  return t('event.ticketsFromTo', { min: formatPrice(min), max: formatPrice(max) });
}

/* ------------------------------------------------------------------ */
/* Main content + sidebar                                              */
/* ------------------------------------------------------------------ */
function buildDetailSection(event) {
  const container = el('div', { className: 'container' });
  const grid = el('div', { className: 'detail-grid' });

  grid.append(buildProse(event), buildSideColumn(event));
  container.append(grid);
  return container;
}

/** Full description, purpose, the registration list and organiser information. */
function buildProse(event) {
  const prose = el('div', { className: 'prose' });

  prose.append(el('h2', { text: t('event.aboutHeading') }));
  // The description is one paragraph per blank line, so a long text stays
  // readable without trusting it as HTML.
  event.description
    .split(/\n+/)
    .filter((paragraph) => paragraph.trim() !== '')
    .forEach((paragraph) => {
      prose.append(el('p', { text: paragraph.trim() }));
    });

  prose.append(el('h2', { text: t('event.purposeHeading') }));
  prose.append(el('p', { text: event.purpose }));

  prose.append(el('h2', { text: t('event.fundsHeading') }));
  const uses = el('ul');
  [t('event.funds1'), t('event.funds2'), t('event.funds3')].forEach((line) =>
    uses.append(el('li', { text: line }))
  );
  prose.append(uses);

  // A3: the registration list, and the weather panel, both sit in the main
  // column so the wide table has room to breathe.
  prose.append(buildRegistrationsSection(event));
  prose.append(buildWeatherPlaceholder(event));

  prose.append(el('h2', { text: t('event.accessHeading') }));
  prose.append(el('p', { text: t('event.accessBody') }));

  prose.append(el('h2', { text: t('event.statusHeading') }));
  prose.append(
    el('p', {
      text:
        event.eventState === 'past'
          ? t('event.statusPast', { date: formatDate(event.dateEnd) })
          : event.eventState === 'ongoing'
            ? t('event.statusOngoing')
            : t('event.statusUpcoming', { date: formatDateRange(event) }),
    })
  );

  return prose;
}

