/**
 * The list of registrations, newest purchase first.
 *
 * The order is decided by the API (`ORDER BY registered_at DESC`), so this
 * function renders the array in the order it arrives and does not sort again -
 * one place decides the order, which is what the brief asks for: "sorted by the
 * latest date when the tickets were purchased".
 *
 * Built as a real <table> because the data is tabular, with a caption and
 * column headers so a screen reader can navigate it. The CSS that styles it
 * lives in the "registrations table" section of styles.css.
 */
function buildRegistrationsSection(event) {
  const registrations = event.registrations || [];

  const heading = el('h2', {
    text: t('event.registrationsHeading'),
    attributes: { id: 'registrations-heading' },
  });
  const section = el('section', {
    className: 'registrations',
    attributes: { 'aria-labelledby': 'registrations-heading' },
  });
  section.append(heading);

  if (registrations.length === 0) {
    section.append(
      el('p', { className: 'registrations__empty', text: t('event.registrationsEmpty') })
    );
    return section;
  }

  section.append(
    el('p', {
      className: 'registrations__lead',
      text: t('event.registrationsLead', { count: registrations.length }),
    })
  );

  const wrapper = el('div', { className: 'table-wrap' });
  const table = el('table', { className: 'data-table' });

  const caption = el('caption', {
    className: 'sr-only',
    text: t('event.registrationsHeading'),
  });
  table.append(caption);

  const head = el('thead');
  const headRow = el('tr');
  [
    t('event.registrationsName'),
    t('event.registrationsTier'),
    t('event.registrationsTickets'),
    t('event.registrationsValue'),
    t('event.registrationsDate'),
  ].forEach((label, index) => {
    headRow.append(
      el('th', {
        text: label,
        attributes: { scope: 'col', class: index >= 2 ? 'is-numeric' : '' },
      })
    );
  });
  head.append(headRow);
  table.append(head);

  const body = el('tbody');
  registrations.forEach((registration) => {
    const row = el('tr');

    // The attendee cell carries the name plus the contact details underneath,
    // so the table stays narrow on a phone while still showing the email.
    const attendee = el('th', { attributes: { scope: 'row' } });
    attendee.append(
      el('span', { className: 'data-table__primary', text: registration.attendeeName })
    );
    const contact = [registration.attendeeEmail, registration.attendeePhone]
      .filter(Boolean)
      .join(' · ');
    if (contact) {
      attendee.append(el('span', { className: 'data-table__secondary', text: contact }));
    }
    // A registration without a name would be a database problem, not a display
    // one, but a fallback keeps the table readable either way.
    if (!registration.attendeeName) {
      attendee.textContent = t('event.registrationsLogin') + ' ' + registration.registrationId;
    }

    row.append(
      attendee,
      el('td', {
        text: registration.ticketName || t('event.tierGeneral'),
      }),
      el('td', {
        className: 'is-numeric',
        text: String(registration.ticketsPurchased),
      }),
      el('td', {
        className: 'is-numeric',
        text: formatCurrency(registration.totalAmount),
      }),
      el('td', {
        // registeredAt is a DATETIME string; only the date is useful in a table,
        // and the exact time is kept in the title attribute.
        text: formatShortDate(String(registration.registeredAt).slice(0, 10)),
        attributes: { title: registration.registeredAt },
      })
    );
    body.append(row);
  });
  table.append(body);

  // A totals row, so the "how much has this raised in tickets" question is
  // answered without adding up the column by hand.
  const foot = el('tfoot');
  const footRow = el('tr');
  footRow.append(
    el('th', { text: t('event.registrationsTotal'), attributes: { scope: 'row' } }),
    el('td', { text: '' }),
    el('td', {
      className: 'is-numeric',
      text: String(event.totalTicketsSold || 0),
    }),
    el('td', {
      className: 'is-numeric',
      text: formatCurrency(
        registrations.reduce((sum, row) => sum + Number(row.totalAmount || 0), 0)
      ),
    }),
    el('td', { text: '' })
  );
  foot.append(footRow);
  table.append(foot);

  wrapper.append(table);
  section.append(wrapper);
  return section;
}

