/**
 * A placeholder that loadForecast() replaces (or removes).
 *
 * A placeholder rather than a fetch inside renderEvent() because the forecast
 * is a separate, optional network call to a third party: the page must be
 * complete and usable before - and even without - it.
 */
function buildWeatherPlaceholder() {
  const section = el('section', {
    className: 'weather',
    attributes: { id: 'weather-panel', 'aria-live': 'polite' },
  });
  section.append(el('h2', { text: t('weather.heading') }));
  section.append(el('p', { className: 'weather__loading', text: t('weather.loading') }));
  return section;
}

/** The forecast panel, once the data has arrived. */
function buildWeatherPanel(event, forecast) {
  const section = el('section', {
    className: 'weather',
    attributes: { id: 'weather-panel' },
  });

  section.append(el('h2', { text: t('weather.heading') }));
  section.append(
    el('p', {
      className: 'weather__lead',
      // The venue name already contains its city ("Lismore Riverside Park"), so
      // the lead puts the venue first and the city in brackets rather than
      // gluing the two together, which produced "LismoreLismore Riverside Park".
      text: t('weather.lead', {
        venue: forecast.venueName,
        city: forecast.city,
        date: formatDate(forecast.date),
      }),
    })
  );

  const card = el('div', {
    className: isWetWeather(forecast.weatherCode)
      ? 'weather__card weather__card--wet'
      : 'weather__card',
  });

  const glyph = el('span', {
    className: 'weather__glyph',
    text: weatherGlyph(forecast.weatherCode),
    attributes: { 'aria-hidden': 'true' },
  });

  const summary = el('div', { className: 'weather__summary' });
  summary.append(
    el('span', {
      className: 'weather__code',
      text: t(weatherCodeKey(forecast.weatherCode)),
    })
  );
  const temperatures = [];
  if (forecast.temperatureMax !== null) {
    temperatures.push(`${t('weather.high')} ${Math.round(forecast.temperatureMax)}°C`);
  }
  if (forecast.temperatureMin !== null) {
    temperatures.push(`${t('weather.low')} ${Math.round(forecast.temperatureMin)}°C`);
  }
  if (temperatures.length > 0) {
    summary.append(el('span', { className: 'weather__temps', text: temperatures.join('  ·  ') }));
  }

  card.append(glyph, summary);

  const details = el('ul', { className: 'weather__details' });
  if (forecast.rainChance !== null) {
    details.append(
      el('li', {
        text: `${t('weather.rainChance')}: ${Math.round(forecast.rainChance)}%`,
      })
    );
  }
  if (forecast.windMax !== null) {
    details.append(
      el('li', {
        text: `${t('weather.wind')}: ${Math.round(forecast.windMax)} km/h`,
      })
    );
  }
  if (details.childElementCount > 0) card.append(details);

  section.append(card);
  section.append(el('p', { className: 'weather__hint', text: t('weather.outdoorHint') }));
  section.append(
    el('p', {
      className: 'weather__credit',
      text: t('weather.attribution'),
    })
  );

  return section;
}

/** Registration, tickets and the goal progress bar. */
function buildSideColumn(event) {
  const column = el('div', { className: 'side-column' });

  column.append(
    buildGoalPanel(event),
    buildTicketPanel(event),
    buildOrganiserPanel(event)
  );

  return column;
}

/** Goal vs progress - the fundraising goal against the donations recorded. */
function buildGoalPanel(event) {
  const panel = el('div', { className: 'panel panel--brand' });
  panel.append(el('h2', { text: t('event.goalHeading') }));
  panel.append(el('p', { text: t('event.goalLead', { organisation: event.organizationName }) }));
  panel.append(progressBar(event));

  const summary = el('ul', { className: 'contact-list' });
  [
    [t('event.goalRow'), formatCurrency(event.goalAmount)],
    [t('event.raisedRow'), formatCurrency(event.raisedAmount)],
    [t('event.remainingRow'), formatCurrency(Math.max(event.goalAmount - event.raisedAmount, 0))],
    [t('event.donationsRow'), t('event.donationsValue', { count: event.donationCount || 0 })],
  ].forEach(([label, value]) => {
    const item = el('li');
    item.append(el('span', { text: label }), el('span', { text: value }));
    summary.append(item);
  });
  panel.append(summary);

  return panel;
}

/**
 * Ticket tiers and the Register button.
 *
 * A3: the button is now an ANCHOR to the registration page carrying the event
 * id in the query string, which is the navigation the brief asks for. A past
 * event shows a disabled button instead, because there is nothing left to book.
 */
function buildTicketPanel(event) {
  const panel = el('div', { className: 'panel panel--accent' });
  panel.append(el('h2', { text: t('event.ticketsHeading') }));

  const tickets = event.ticketTypes || [];

  if (tickets.length === 0) {
    panel.append(el('p', { text: t('event.ticketsMissing') }));
  } else {
    const list = el('ul', { className: 'ticket-list' });
    tickets.forEach((ticket) => {
      const item = el('li', {
        className: ticket.price === 0 ? 'ticket ticket--free' : 'ticket',
      });

      const name = el('span', { className: 'ticket__name', text: ticket.ticketName });
      if (ticket.description) {
        name.append(el('span', { className: 'ticket__desc', text: ticket.description }));
      }
      if (ticket.quantityAvailable !== null && ticket.quantityAvailable !== undefined) {
        name.append(
          el('span', {
            className: 'ticket__availability',
            text:
              ticket.quantityAvailable > 0
                ? t('event.availableCount', { count: ticket.quantityAvailable })
                : t('event.soldOut'),
          })
        );
      }

      item.append(
        name,
        el('span', {
          className: 'ticket__price',
          text: ticket.price === 0 ? t('event.free') : formatPrice(ticket.price),
        })
      );
      list.append(item);
    });
    panel.append(list);
  }

  if (event.eventState === 'past') {
    // A <button disabled> rather than a dead link: there is nothing to book.
    panel.append(
      el('button', {
        className: 'button button--block',
        text: t('event.registerClosed'),
        attributes: { type: 'button', id: 'register-button', disabled: 'disabled' },
      })
    );
  } else {
    panel.append(
      el('a', {
        className: 'button button--block',
        text: t('event.register'),
        attributes: {
          id: 'register-button',
          // The event id travels in the query string, exactly as the brief
          // suggests: "You may utilise appropriate methods (e.g., URL Query
          // Strings or Local Storage) to pass the event ID between pages".
          href: `${REGISTRATION_PAGE}?id=${encodeURIComponent(event.eventId)}`,
        },
      })
    );
  }

  /*
   * The old A2 paragraph used to sit here ("Registering and paying for tickets
   * online is being built in Assessment 3"). It has been removed on purpose:
   * Assessment 3 built that feature, so the sentence was both out of date and
   * misleading, and the form it referred to is gone as well - the button above
   * now links to registration.html.
   */

  return panel;
}

/** Contact panel for the organisation running the event. */
function buildOrganiserPanel(event) {
  const panel = el('div', { className: 'panel' });
  panel.append(el('h2', { text: t('event.organisedBy') }));
  panel.append(el('h3', { text: event.organizationName }));
  panel.append(el('p', { text: t('event.organiserBody') }));
  const list = el('ul', { className: 'contact-list' });
  const city = el('li');
  city.append(el('span', { text: t('event.basedIn') }), el('span', { text: event.city }));
  list.append(city);
  panel.append(list);
  panel.append(
    // An anchor, not a paragraph. This was built with el('p', ...) carrying an
    // href and the .button classes, so it looked exactly like a button and did
    // nothing at all when clicked: a paragraph has no href behaviour.
    el('a', {
      className: 'button button--small button--outline',
      text: t('event.moreEvents'),
      attributes: { href: 'search.html' },
    })
  );
  return panel;
}

