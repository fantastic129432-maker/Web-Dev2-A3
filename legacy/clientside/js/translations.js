/** Key/value maps, one per language code. */
export const DICTIONARIES = { en, zh, vi, ja };

/** The language used when nothing else is known. */
export const DEFAULT_LANGUAGE = 'en';

/**
 * Look up a key in the active dictionary.
 *
 * @param {object} options
 * @param {string} options.language  active language code
 * @param {string} options.key       dictionary key
 * @param {object} [options.values]  values for {placeholders}
 * @returns {string} the translated text, or the key itself when missing
 */
export function translate({ language, key, values }) {
  const dictionary = DICTIONARIES[language] || DICTIONARIES[DEFAULT_LANGUAGE];
  let text = dictionary[key];

  // Fall back to English so a missing translation shows real words rather than
  // a raw key, and log it once so the gap is easy to find during development.
  if (text === undefined) {
    text = DICTIONARIES[DEFAULT_LANGUAGE][key];
    if (text === undefined) {
      console.warn(`[i18n] missing key: ${key}`);
      return key;
    }
  }

  if (!values) return text;

  return text.replace(/\{(\w+)\}/g, (match, name) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match
  );
}

