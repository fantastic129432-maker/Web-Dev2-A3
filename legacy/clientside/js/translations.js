/**
 * js/translations.js
 * ---------------------------------------------------------------------------
 * Every piece of user interface text, in four languages.
 *
 * Important scope note: this file translates the INTERFACE only. Event names,
 * descriptions, venues and organisation names come from the database in
 * English, because the assessment brief defines the data layer in English and a
 * translated content layer would need either extra columns or a translation
 * table, which is beyond Assessment 3. The language switch therefore changes
 * the labels, headings, buttons, help text and messages - everything the code
 * owns - and leaves the seeded content as it is.
 *
 * Layout of this file
 *   1. SUPPORTED_LANGUAGES  the four options offered in the switcher
 *   2. DICTIONARIES         one flat key/value map per language
 *   3. helpers              translate(), interpolation and fallback
 *
 * Keys are grouped by area so a missing key is easy to spot:
 *   nav.*      menu and footer
 *   common.*   shared words such as Loading or Close
 *   home.*     home page
 *   search.*   search page
 *   event.*    event detail page
 *   card.*     event card summary
 *   state.*    the derived event state
 *   error.*    messages shown when a request fails
 *   a11y.*     labels that only assistive technology reads
 *   settings.* the theme and language controls
 */

