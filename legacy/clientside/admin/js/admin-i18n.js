const DICTIONARIES = { en, zh, vi, ja };

/** The language codes this module accepts. */
const CODES = SUPPORTED_LANGUAGES.map((language) => language.code);

/**
 * The active language.
 *
 * Read once at module load. The public site's i18n module reads the same key,
 * so a value written by either site applies to both.
 */
let current = (() => {
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored && CODES.includes(stored)) return stored;
  } catch (error) {
    // Private browsing can block localStorage; English is a safe default.
  }
  return DEFAULT_LANGUAGE;
})();

/** The listeners told when the language changes. */
const listeners = [];

/** The active language code: 'en', 'zh', 'vi' or 'ja'. */
export function getLanguage() {
  return current;
}

/** The entry from SUPPORTED_LANGUAGES for the active language. */
export function getLanguageInfo() {
  return (
    SUPPORTED_LANGUAGES.find((language) => language.code === current) ||
    SUPPORTED_LANGUAGES[0]
  );
}

/** Every language the switcher offers, for building the control. */
export function availableLanguages() {
  return SUPPORTED_LANGUAGES;
}

/**
 * Look up one string.
 *
 * `values` fills the {placeholders} in the text, e.g.
 *   t('delete.success', { name: event.eventName })
 *
 * A missing key falls back to English, then to the key itself, so a gap shows up
 * as a readable label rather than as "undefined" on the page.
 */
export function t(key, values) {
  const dictionary = DICTIONARIES[current] || DICTIONARIES[DEFAULT_LANGUAGE];
  let text = dictionary[key];
  if (text === undefined) text = DICTIONARIES[DEFAULT_LANGUAGE][key];
  if (text === undefined) return key;

  if (!values) return text;

  return text.replace(/\{(\w+)\}/g, (match, name) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match
  );
}

/**
 * Replace the static text in a page with the current language.
 *
 * The admin pages carry their headings and labels in the HTML so a page reads
 * sensibly before the scripts run. This walks those markers and swaps the text:
 *
 *   <h1 data-i18n="dash.heading">Overview</h1>
 *   <input data-i18n-attr="placeholder:events.filterKeywordPlaceholder">
 *
 * The same two attributes the public site uses (js/i18n.js), so the markup means
 * the same thing on both sites.
 *
 * This is why the interface was half English at first: the header and menu are
 * built by admin.js and went through t(), but everything written directly in the
 * HTML had no marker and nothing ever rewrote it. A translated dictionary is not
 * enough on its own - the page has to be told which string belongs where.
 *
 * Text is set with textContent, never innerHTML, so a translation cannot inject
 * markup. A key that is missing leaves the original English in place rather than
 * blanking the element.
 */
export function applyTranslations(scope = document) {
  scope.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.getAttribute('data-i18n');
    const text = t(key);
    if (text !== key) element.textContent = text;
  });

  scope.querySelectorAll('[data-i18n-attr]').forEach((element) => {
    const pairs = element.getAttribute('data-i18n-attr').split(',');
    pairs.forEach((pair) => {
      const separator = pair.indexOf(':');
      if (separator === -1) return;

      const attribute = pair.slice(0, separator).trim();
      const key = pair.slice(separator + 1).trim();
      const text = t(key);
      if (attribute && text !== key) element.setAttribute(attribute, text);
    });
  });
}

/** Redraw when the language changes. */
export function onLanguageChange(callback) {
  listeners.push(callback);
}

/**
 * Switch language.
 *
 * The stored value is the same one the public site reads, which is what keeps
 * the two sites in step. Setting the same language twice does nothing, so a
 * caller can call it from a change handler without causing a redraw loop.
 */
export function setLanguage(language) {
  if (!CODES.includes(language) || language === current) return;

  current = language;

  try {
    window.localStorage.setItem(STORAGE_KEY, language);
  } catch (error) {
    // Private browsing: the choice simply does not persist.
  }

  // Keep the document's lang attribute honest, which screen readers and the
  // browser's own hyphenation both use.
  const info = getLanguageInfo();
  document.documentElement.setAttribute('lang', info.htmlLang || info.code);

  listeners.forEach((callback) => callback(language));
}
