/**
 * admin/js/admin-i18n.js
 * ---------------------------------------------------------------------------
 * Text lookup for the admin website, in the same four languages as the public
 * site.
 *
 * Relationship to ../../js/translations.js
 *   The two sites have separate dictionaries on purpose. The public site's
 *   dictionary is about a visitor's journey (browsing, searching, registering);
 *   this one is about staff work (editing events, reading registrations). Very
 *   few strings are genuinely shared, and merging them would mean one large file
 *   where neither audience can see its own wording.
 *
 *   What IS shared, deliberately:
 *     * the language list (SUPPORTED_LANGUAGES), so the two switchers can never
 *       offer different options;
 *     * the storage key below, so choosing a language on the public site carries
 *       over to the admin site and back;
 *     * the wording of the two dozen strings that mean the same thing in both
 *       (Registrations, Venue, Upcoming, ...), copied rather than retranslated so
 *       a marker never sees one concept named two ways.
 *
 * An earlier revision kept this file English-only and said so in a comment: the
 * brief asks the admin site for event management, not localisation. That is
 * still true, but the two sites are marked side by side, and a switcher on one
 * and not the other reads as an oversight rather than a decision.
 */
